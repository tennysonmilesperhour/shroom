// Optional local PostgreSQL verification; PGLITE_MODULE can point at a temporary install.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const { PGlite } = await import(process.env.PGLITE_MODULE ?? '@electric-sql/pglite');
const root=fileURLToPath(new URL('../../',import.meta.url));
const patch=JSON.parse(fs.readFileSync(root+'docs/strain-profile-research-2026-09-25.json'));
const apply=execFileSync('python3',[root+'supabase/maintenance/render_profile_patch.py','apply'],{encoding:'utf8'});
const restore=execFileSync('python3',[root+'supabase/maintenance/render_profile_patch.py','restore'],{encoding:'utf8'});
const db=new PGlite();
await db.exec('CREATE TABLE strains (id bigint primary key, name text, mushroom_type text, experience_summary text, profile_source text, spectrum_hue integer, experience_tags text[], evidence_grade text, alkaloid_total_pct numeric)');
for(const {id,name,before:r} of patch) await db.query('INSERT INTO strains VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)',[id,name,'psychedelic',r.experience_summary,r.profile_source,r.spectrum_hue,r.experience_tags,r.evidence_grade,r.alkaloid_total_pct]);
await db.exec("INSERT INTO strains VALUES (1,'Existing profile','psychedelic','Keep this','Original',180,ARRAY['existing'],'mixed',1.2)");
const snapshot=async()=> (await db.query('SELECT * FROM strains ORDER BY id')).rows;
const before=await snapshot();
await db.exec(apply);const after=await snapshot();
assert.equal(after.filter((r,i)=>JSON.stringify(r)!==JSON.stringify(before[i])).length,42);
assert.deepEqual(after[0],before[0]);
await db.exec(apply);assert.deepEqual(await snapshot(),after);
await db.exec(restore);assert.deepEqual(await snapshot(),before);
await db.exec(restore);assert.deepEqual(await snapshot(),before);
await db.query("UPDATE strains SET experience_tags=ARRAY['new user tag'] WHERE id=19");
const edited=await snapshot();
await assert.rejects(db.exec(apply),/content changed/);assert.deepEqual(await snapshot(),edited);
await db.query("UPDATE strains SET experience_tags=ARRAY[]::text[] WHERE id=19");
await db.exec(apply);
await db.query("UPDATE strains SET profile_source='Later edit' WHERE id=21");
const later=await snapshot();
await assert.rejects(db.exec(restore),/content changed/);assert.deepEqual(await snapshot(),later);
console.log('PASS: atomic patch, idempotency, exact restoration, and concurrent-edit protection');
await db.close();
